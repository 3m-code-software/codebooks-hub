export function getRandomIdeas(category: Category, count: number = 4): Idea[] {
  const ideas = IDEAS_BY_CATEGORY[category];
  const shuffled = [...ideas].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}

export function getAllIdeas(): Idea[] {
  return Object.values(IDEAS_BY_CATEGORY).flat();
}

export function getIdeasByCategory(category: Category): Idea[] {
  return IDEAS_BY_CATEGORY[category];
}
